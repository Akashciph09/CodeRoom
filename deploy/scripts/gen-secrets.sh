#!/usr/bin/env bash
# Create deploy/.env with fresh secrets. Run once per server; never commit the result.
#   deploy/scripts/gen-secrets.sh https://app.<ip>.sslip.io https://api.<ip>.sslip.io
set -euo pipefail
cd "$(dirname "$0")/.."

APP_URL=${1:?usage: gen-secrets.sh <app-url> <api-url>}
API_URL=${2:?usage: gen-secrets.sh <app-url> <api-url>}
if [ -e .env ]; then
  echo "deploy/.env already exists — refusing to overwrite (the database password and signing key are in it)." >&2
  exit 1
fi

# Hex only, so the password is safe inside connection URLs without escaping.
hex() { openssl rand -hex "$1"; }

# ES256 signing key as a private JWK set (the format GoTrue's GOTRUE_JWT_KEYS takes). Generated in a
# throwaway Node container so the server doesn't need Node installed.
JWKS=$(docker run --rm node:22-alpine node -e '
  const { generateKeyPairSync, randomUUID } = require("node:crypto");
  const { privateKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
  const jwk = privateKey.export({ format: "jwk" });
  console.log(JSON.stringify([{ ...jwk, kid: randomUUID(), use: "sig", alg: "ES256", key_ops: ["sign", "verify"] }]));
')

umask 077
cat > .env <<EOF
# Generated by deploy/scripts/gen-secrets.sh on $(date -u +%F). Secret: never commit or share.
APP_URL=${APP_URL}
API_URL=${API_URL}
POSTGRES_PASSWORD=$(hex 24)
AUTH_JWT_SECRET=$(hex 32)
AUTH_JWT_KEYS='${JWKS}'
# AUTH_DISABLE_SIGNUP=true   # close sign-ups once your accounts exist
# WORKER_CONCURRENCY=2
EOF
echo "Wrote deploy/.env (mode 600). Back it up somewhere safe: without it the database can't be opened"
echo "and every session is invalidated."
